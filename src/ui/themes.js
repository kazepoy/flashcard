/** Applique un thème ; « auto » ou un identifiant inconnu (réglage venu d'une version plus récente) suit le système. */
export function applyTheme(id, doc = document) {
  const root = doc.documentElement;
  const th = THEMES.find((x) => x.id === id);
  let el = doc.getElementById('theme-vars');
  if (th) root.dataset.theme = th.base;
  else delete root.dataset.theme;
  if (!th || th.id === th.base) {
    el?.remove();
    return;
  }
  if (!el) doc.head.append((el = Object.assign(doc.createElement('style'), { id: 'theme-vars' })));
  const decls = Object.entries({ ...th.colors, ...th.fonts })
    .map(([k, v]) => `--${k}: ${v};`)
    .join(' ');
  // même spécificité que :root[data-theme='dark'] de styles.css, déclarée après : l'emporte
  el.textContent = `@media screen { html:root[data-theme] { ${decls} } }`;
}
